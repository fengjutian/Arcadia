import {
  aiChat,
  getDocument,
  updateAutoTags,
} from '../../api'
import type { AIProvider, Task } from '../../types'
import { buildAutoTagPrompt, mergeAutoTags, parseAutoTagResponse } from '../ai/autoTag'
import type { TaskHandler } from './taskWorker'

/** Task kinds handled by the background worker. */
export const TASK_KIND_EMBED = 'embedding.index'
export const TASK_KIND_AUTO_TAG = 'autotag.generate'

function parsePayload(task: Task): Record<string, unknown> {
  try {
    const value: unknown = JSON.parse(task.payload || '{}')
    return typeof value === 'object' && value !== null ? (value as Record<string, unknown>) : {}
  } catch {
    return {}
  }
}

function requireDocumentId(task: Task): string {
  const id = task.documentId ?? parsePayload(task).documentId
  if (typeof id !== 'string' || id.length === 0) {
    throw new Error('task is missing documentId')
  }
  return id
}

/**
 * Drain `embedding.index` rows left by older builds.
 *
 * Indexing now has a single owner: the Rust RAG supervisor (`rag_index_jobs`),
 * which chunks through `document_chunks` and writes chunk-aligned vectors.
 * The old worker re-chunked the document with a different algorithm and wrote
 * `document_embeddings` directly, overwriting the supervisor's rows on every
 * launch. New saves no longer enqueue this task; existing queue rows are
 * acknowledged as no-ops so they stop retrying.
 */
const drainLegacyEmbeddingTask: TaskHandler = async () => {}

/**
 * Derive tags from the document body and merge them with the user's own tags.
 *
 * Existing tags always win: generated tags are prepended and `mergeAutoTags`
 * de-duplicates, so a user-curated tag is never dropped. Any failure is recorded
 * by the task queue rather than blocking the save that queued it.
 */
export function createAutoTagHandler(provider: AIProvider): TaskHandler {
  return async (task: Task) => {
    const documentId = requireDocumentId(task)
    const document = await getDocument(documentId)
    const markdown = document.markdown ?? document.summary ?? ''
    if (markdown.trim().length === 0) return

    const request = buildAutoTagPrompt({
      markdown,
      existingTags: document.tags,
      title: document.title,
    })
    const response = await aiChat(provider.id, request)
    const generated = parseAutoTagResponse(response.content)
    if (generated.length === 0) return
    // Preserve any tags generated by a previous run; `mergeAutoTags` also keeps
    // the user's own curated tags, which must never be dropped.
    const merged = mergeAutoTags(generated, document.autoTags ?? [])
    await updateAutoTags(documentId, merged)
  }
}

/** Build the handler map for the configured provider. */
export function createTaskHandlers(provider: AIProvider): Record<string, TaskHandler> {
  return {
    [TASK_KIND_AUTO_TAG]: createAutoTagHandler(provider),
    [TASK_KIND_EMBED]: drainLegacyEmbeddingTask,
  }
}